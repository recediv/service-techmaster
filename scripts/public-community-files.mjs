import fs from 'node:fs/promises';
import path from 'node:path';
import crypto from 'node:crypto';
import { redactCommunityContacts } from './public-community-privacy.mjs';

const hash = bytes => crypto.createHash('sha256').update(bytes).digest('hex');
const ownedName = /^consultations-([a-f0-9]{20})\.json$/;
const within = (root, target) => { const relative = path.relative(root, target); return relative && !relative.startsWith('..') && !path.isAbsolute(relative); };

async function communityDirectory(projectRoot) {
  const root = await fs.realpath(projectRoot), publicRoot = path.join(root, 'public'), directory = path.join(publicRoot, 'community');
  for (const item of [publicRoot, directory]) {
    const info = await fs.lstat(item); if (!info.isDirectory() || info.isSymbolicLink() || !within(root, await fs.realpath(item))) throw new Error('Unsafe public community directory.');
  }
  return { root, directory };
}

// Remove only verified files generated by this importer. A mismatched filename,
// payload schema, hash, or symlink fails closed and leaves that input untouched.
export async function pruneCommunityPayloads({ projectRoot, keepUrl, backupDirectory }) {
  const { root, directory } = await communityDirectory(projectRoot), keepName = path.basename(keepUrl);
  if (!ownedName.test(keepName) || keepUrl !== '/community/' + keepName) throw new Error('Invalid current community payload URL.');
  const backup = path.resolve(backupDirectory);
  if (!within(path.join(root, '.local'), backup)) throw new Error('Community backups must stay inside ignored local storage.');
  const candidates = [];
  for (const entry of await fs.readdir(directory, { withFileTypes: true })) {
    const match = entry.name.match(ownedName); if (!match || entry.name === keepName) continue;
    const target = path.join(directory, entry.name), info = await fs.lstat(target);
    if (!info.isFile() || info.isSymbolicLink() || !within(directory, await fs.realpath(target))) throw new Error('Unsafe historical community payload.');
    const bytes = await fs.readFile(target), payload = JSON.parse(bytes);
    if (hash(bytes).slice(0, 20) !== match[1] || payload.schemaVersion !== 1 || !Array.isArray(payload.consultations) || !payload.filters || Object.keys(payload).sort().join(',') !== 'consultations,filters,schemaVersion') throw new Error('Historical community payload is not a verified importer artifact.');
    candidates.push({ name: entry.name, target, bytes, sha256: hash(bytes) });
  }
  await fs.mkdir(backup, { recursive: true });
  for (const candidate of candidates) {
    const destination = path.join(backup, candidate.name);
    await fs.writeFile(destination, candidate.bytes, { flag: 'wx' }).catch(async error => { if (error.code !== 'EEXIST' || hash(await fs.readFile(destination)) !== candidate.sha256) throw error; });
    if (hash(await fs.readFile(candidate.target)) !== candidate.sha256) throw new Error('Historical community payload changed before safe cleanup.');
    await fs.unlink(candidate.target);
  }
  return candidates.map(({ name, sha256, bytes }) => ({ name, sha256, bytes: bytes.length }));
}

export async function auditCommunityJsonPrivacy({ projectRoot }) {
  const { directory } = await communityDirectory(projectRoot); let files = 0, strings = 0, verifiedCatalogStrings = 0;
  const catalogFile = path.join(projectRoot, 'data/generated/resources.json');
  const catalog = new Map(await fs.readFile(catalogFile, 'utf8').then(value => JSON.parse(value).records.map(row => [row.id, row])).catch(error => { if (error.code === 'ENOENT') return []; throw error; }));
  const visit = value => {
    if (typeof value === 'string') { strings++; if (redactCommunityContacts(value) !== value) throw new Error('A public community JSON string contains an author contact candidate.'); }
    else if (value && typeof value === 'object') for (const child of Object.values(value)) visit(child);
  };
  for (const name of await fs.readdir(directory)) {
    if (!name.endsWith('.json')) continue;
    const target = path.join(directory, name), info = await fs.lstat(target);
    if (!info.isFile() || info.isSymbolicLink() || !within(directory, await fs.realpath(target))) throw new Error('Unsafe public community JSON.');
    const json = JSON.parse(await fs.readFile(target, 'utf8'));
    if (json.filters) {
      for (const group of ['types','vendors','models']) for (const row of json.filters[group] || []) {
        const resource = catalog.get(row.id);
        if (!resource || row.title !== resource.title || row.path !== resource.path || row.parentId !== resource.parentId) throw new Error('A community filter is not an exact reviewed public catalog projection.');
        verifiedCatalogStrings += 2;
      }
      // Model identifiers contain phone-like digits; exact catalog equality is
      // their independent proof, while every author field is scanned below.
      const { filters, ...content } = json; visit(content);
    } else visit(json);
    files++;
  }
  return { files, strings, verifiedCatalogStrings, authorContactCandidates: 0 };
}
